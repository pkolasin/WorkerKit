#!/usr/bin/env bash
# Regenerates the checked-in VIES proxy from the local WSDL.
# The solution build does not run this script and does not contact the remote service.
#
#   dotnet tool install --global dotnet-svcutil --version 8.0.0
#   # dotnet-svcutil 8.0.0 runs on the .NET 9 runtime.
#   ./samples/Vies/regenerate-vies.sh
set -euo pipefail

root="$(cd "$(dirname "${BASH_SOURCE[0]}")/../.." && pwd)"
work="${root}/.soapgen"
destination="${root}/samples/Vies/Generated/CheckVatService.cs"

rm -rf "${work}"
mkdir -p "${work}" "$(dirname "${destination}")"

dotnet-svcutil "${root}/samples/Vies/wsdl/checkVatService.wsdl" \
  --outputDir "${work}" \
  --namespace "*,WorkerKit.Samples.Vies.Generated" \
  --targetFramework net10.0 \
  --noLogo

generated="$(find "${work}" -name '*.cs' | head -n 1)"
if [[ -z "${generated}" ]]; then
  echo "dotnet-svcutil did not write a C# file." >&2
  exit 1
fi

# Drop the net6-era CloseAsync. ClientBase already provides it, and a #if in a
# file that is later copied into a template is eaten by the template engine.
python3 - "${generated}" "${destination}" << 'PY'
import pathlib, re, sys

source = pathlib.Path(sys.argv[1]).read_text(encoding="utf-8-sig").replace("\r\n", "\n")
updated, count = re.subn(
    r"\n[ \t]*#if !NET6_0_OR_GREATER\n.*?#endif\n",
    "\n",
    source,
    count=1,
    flags=re.S,
)
if count != 1:
    raise SystemExit("svcutil did not emit the net6 CloseAsync block; update the workaround.")

header = """// Generated by dotnet-svcutil 8.0.0 from samples/Vies/wsdl/checkVatService.wsdl.
// Regenerate with samples/Vies/regenerate-vies.sh. The build does not download the WSDL.
// The net6-era CloseAsync block is removed: ClientBase already provides CloseAsync.

"""
pathlib.Path(sys.argv[2]).write_text(header + updated, encoding="utf-8", newline="\n")
PY

rm -rf "${work}"
echo "Wrote ${destination}"
